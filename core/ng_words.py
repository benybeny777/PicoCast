def apply_ng_word_replacements(text):
    """既知のNGワードをAI修正前後にローカルで置換する。"""
    if not text:
        return text

    result = text
    for source, replacement in sorted(NG_WORD_REPLACEMENTS, key=lambda x: len(x[0]), reverse=True):
        result = result.replace(source, replacement)
    return result
